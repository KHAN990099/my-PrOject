import fs from 'node:fs/promises';
import path from 'node:path';

const DEFAULT_IGNORED = new Set(['node_modules', '.git', 'dist', 'build', 'coverage', '.next', 'vendor']);
const BINARY_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.gif', '.webp', '.ico', '.pdf', '.zip', '.gz', '.tar', '.7z', '.mp3', '.mp4', '.mov', '.woff', '.woff2', '.ttf', '.eot', '.exe', '.dll', '.so', '.bin', '.class', '.pyc']);
const SECRET_NAME = /(^|\/)(\.env(?:\..*)?|.*(?:secret|credential|private[-_]?key|token).*)$/i;
const MAX_FILE_BYTES = 512 * 1024;

export function isSecretPath(relativePath) {
  return SECRET_NAME.test(relativePath.replaceAll('\\', '/'));
}

export function isProbablyBinary(buffer, relativePath) {
  if (BINARY_EXTENSIONS.has(path.extname(relativePath).toLowerCase())) return true;
  return buffer.subarray(0, Math.min(buffer.length, 4096)).includes(0);
}

async function collectFiles(root, relative = '') {
  const current = path.join(root, relative);
  const entries = await fs.readdir(current, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = relative ? path.join(relative, entry.name) : entry.name;
    const normalized = rel.replaceAll('\\', '/');
    if (entry.isDirectory()) {
      if (!DEFAULT_IGNORED.has(entry.name) && !isSecretPath(normalized)) files.push(...await collectFiles(root, rel));
    } else if (entry.isFile() && !isSecretPath(normalized)) {
      files.push({ absolute: path.join(root, rel), relative: normalized });
    }
  }
  return files;
}

function languageFor(file) {
  const ext = path.extname(file).toLowerCase();
  return ({ '.js': 'JavaScript', '.mjs': 'JavaScript', '.cjs': 'JavaScript', '.ts': 'TypeScript', '.tsx': 'TypeScript', '.jsx': 'JavaScript', '.py': 'Python', '.go': 'Go', '.rs': 'Rust', '.java': 'Java', '.rb': 'Ruby', '.php': 'PHP', '.html': 'HTML', '.css': 'CSS', '.json': 'JSON', '.md': 'Markdown', '.yml': 'YAML', '.yaml': 'YAML', '.sh': 'Shell' })[ext] || 'text';
}

function fileSummary(relative, text) {
  const lines = text.split(/\r?\n/).filter(Boolean);
  const heading = lines.find((line) => /^\s*(#|export |class |function |def |package |module )/.test(line));
  return heading ? heading.trim().replace(/^#+\s*/, '').slice(0, 140) : `${languageFor(relative)} source file`;
}

export async function scanProject(root, options = {}) {
  const maxFiles = options.maxFiles ?? 1000;
  const files = await collectFiles(root);
  if (files.length > maxFiles) throw new Error(`Project contains ${files.length} files; maximum is ${maxFiles}.`);
  const records = [];
  for (const file of files) {
    const stat = await fs.stat(file.absolute);
    if (stat.size > MAX_FILE_BYTES) continue;
    const buffer = await fs.readFile(file.absolute);
    if (isProbablyBinary(buffer, file.relative)) continue;
    const text = buffer.toString('utf8').replaceAll('\u0000', '');
    records.push({ path: file.relative, bytes: stat.size, language: languageFor(file.relative), summary: fileSummary(file.relative, text) });
  }
  records.sort((a, b) => a.path.localeCompare(b.path));
  const directories = [...new Set(records.map((record) => path.posix.dirname(record.path)).filter((dir) => dir !== '.'))].sort();
  const languages = [...new Set(records.map((record) => record.language).filter((lang) => lang !== 'text'))].sort();
  const title = options.title || path.basename(path.resolve(root)) || 'Project';
  return { title, files: records, directories, languages, readme: makeReadme(title, records, languages), explainer: makeExplainer(title, records, directories) };
}

function makeReadme(title, files, languages) {
  const topFiles = files.slice(0, 12).map((file) => `- \`${file.path}\` — ${file.summary}`).join('\n') || '- No readable source files were found.';
  return `# ${title}\n\n> A beginner-friendly overview generated by DocForge.\n\n## What this project contains\n\nThis project has **${files.length} readable file${files.length === 1 ? '' : 's'}**${languages.length ? `, mainly using ${languages.join(', ')}` : ''}.\n\n## Quick start\n\n1. Open the project folder in your editor.\n2. Look at the files listed below to find the main entry point.\n3. Read the project\'s own package or configuration file for the exact run command.\n\n## Important files\n\n${topFiles}\n\n## Project layout\n\nSee the Project Explainer for a file-by-file tour. Generated documentation intentionally omits secrets, dependencies, build output, binary files, and very large files.\n\n## Notes\n\nThis README was generated locally and deterministically by DocForge. No external AI service or network connection was used.\n`;
}

function makeExplainer(title, files, directories) {
  const folderSection = directories.length ? directories.map((dir) => `- **${dir}/** — contains ${files.filter((file) => file.path.startsWith(`${dir}/`)).length} readable file(s).`).join('\n') : '- The project has no nested folders in the readable scan.';
  const fileSection = files.length ? files.map((file) => `- **${file.path}** (${file.language}, ${file.bytes} bytes) — ${file.summary}.`).join('\n') : '- No readable files were found.';
  return `# Project Explainer: ${title}\n\n## Folders\n\n${folderSection}\n\n## Files\n\n${fileSection}\n\n## Safety and scope\n\nDocForge skips dependency folders, version-control metadata, build output, binary files, oversized files, and names that look like secrets.\n`;
}
